"""Abstract base class interface for agent adapters."""

from abc import ABC, abstractmethod
from typing import Any

from pydantic import BaseModel


class AgentObservation(BaseModel):
    """Observation returned to the agent from the environment sandbox."""

    output: str
    error: str | None = None
    exit_code: int = 0
    metadata: dict[str, Any] = {}


class BaseAgentAdapter(ABC):
    """Abstract Base Class for wrapping autonomous AI agents under benchmark evaluation."""

    def __init__(self, agent_id: str, config: dict[str, Any]) -> None:
        self.agent_id = agent_id
        self.config = config

    @abstractmethod
    async def reset(self) -> None:
        """Reset internal agent memory / context state for a clean benchmark run."""
        pass

    @abstractmethod
    async def step(self, observation: AgentObservation) -> str:
        """Execute a single agent reasoning / action step.

        Args:
            observation: Feedback/output from previous action in the environment.

        Returns:
            The code string or command generated by the agent to run in environment.
        """
        pass
